import type { SupabaseClient } from '@supabase/supabase-js'

type DB = SupabaseClient

/**
 * Shared "which broadcast generated this deal" rule for every report
 * surface that attributes deals to broadcasts (Transmissões, ROI de
 * Transmissões, the single-broadcast detail page) — last touch within
 * 30 days before the deal was created, keyed by the contact's
 * normalized PHONE rather than contact_id.
 *
 * Mirrors get_pipeline_dashboard's ticket-based attribution (Pipeline
 * & Vendas: `t.opened_at <= d.created_at and t.opened_at >= d.created_at
 * - 30 days`, most recent wins) so the two reports can't drift onto
 * different definitions of "generated by a campaign" again. Phone
 * instead of contact_id so a contact re-imported under a new id after
 * the broadcast (CSV re-upload, merge that never ran, etc.) still
 * resolves to its touch history — contact_id breaks the instant a
 * duplicate contact exists; phone survives it.
 */
export const BROADCAST_ATTRIBUTION_WINDOW_DAYS = 30

export interface BroadcastTouch {
  broadcastId: string
  /** ISO timestamp — broadcasts.created_at for this touch. */
  createdAt: string
}

/** phone_normalized -> every broadcast that reached that phone in the
 *  loaded window, unsorted (findLastTouch scans the whole list). */
export type TouchesByPhone = Map<string, BroadcastTouch[]>

const CHUNK = 200

/**
 * Loads every broadcast touch (recipient actually received it — same
 * RECEIVED_STATUSES convention as every other broadcast report) whose
 * broadcast.created_at falls in [sinceISO, untilISO], indexed by the
 * recipient's normalized phone. RLS scopes everything to the caller's
 * account — no explicit account_id filter needed, matching every
 * other query in this report family.
 *
 * Three round trips (broadcasts → recipients → contacts), each
 * chunked, rather than one query with a cross-table filter — matches
 * the existing chunking pattern in broadcast-roi-queries.ts /
 * broadcasts-queries.ts (PostgREST's URL length limit bites a single
 * `.in(...)` well before a few hundred UUIDs).
 */
export async function loadTouchesByPhone(
  db: DB,
  args: { sinceISO: string; untilISO: string },
): Promise<TouchesByPhone> {
  const { data: broadcastsData, error: broadcastsError } = await db
    .from('broadcasts')
    .select('id, created_at')
    .gte('created_at', args.sinceISO)
    .lte('created_at', args.untilISO)
  if (broadcastsError) throw broadcastsError
  const broadcasts = (broadcastsData ?? []) as { id: string; created_at: string }[]
  if (broadcasts.length === 0) return new Map()

  const createdAtByBroadcast = new Map(broadcasts.map((b) => [b.id, b.created_at]))
  const broadcastIds = broadcasts.map((b) => b.id)

  const recipientRows: { broadcast_id: string; contact_id: string }[] = []
  for (let i = 0; i < broadcastIds.length; i += CHUNK) {
    const chunk = broadcastIds.slice(i, i + CHUNK)
    const { data, error } = await db
      .from('broadcast_recipients')
      .select('broadcast_id, contact_id')
      .in('broadcast_id', chunk)
      .in('status', ['sent', 'delivered', 'read', 'replied'])
      .not('contact_id', 'is', null)
    if (error) throw error
    recipientRows.push(...((data ?? []) as { broadcast_id: string; contact_id: string }[]))
  }
  if (recipientRows.length === 0) return new Map()

  const contactIds = [...new Set(recipientRows.map((r) => r.contact_id))]
  const phoneByContact = new Map<string, string>()
  for (let i = 0; i < contactIds.length; i += CHUNK) {
    const chunk = contactIds.slice(i, i + CHUNK)
    // is_internal (migration 127) excludes internal/test contacts (e.g.
    // the team's own number used to test flows/broadcasts) from ever
    // populating a phone's touch history — a deal on that same contact
    // can then never resolve a touch and never gets attributed to a
    // broadcast's revenue. Found after an internal test contact
    // accumulated 11 real-customer-named deals with no actual broadcast
    // touch of its own; this guards the case where it (or another
    // internal contact) someday does receive one.
    const { data, error } = await db
      .from('contacts')
      .select('id, phone_normalized')
      .in('id', chunk)
      .eq('is_internal', false)
    if (error) throw error
    for (const c of (data ?? []) as { id: string; phone_normalized: string | null }[]) {
      if (c.phone_normalized) phoneByContact.set(c.id, c.phone_normalized)
    }
  }

  const touchesByPhone: TouchesByPhone = new Map()
  for (const r of recipientRows) {
    const phone = phoneByContact.get(r.contact_id)
    const createdAt = createdAtByBroadcast.get(r.broadcast_id)
    if (!phone || !createdAt) continue
    if (!touchesByPhone.has(phone)) touchesByPhone.set(phone, [])
    touchesByPhone.get(phone)!.push({ broadcastId: r.broadcast_id, createdAt })
  }
  return touchesByPhone
}

/**
 * The most recent touch within the attribution window before
 * `dealCreatedAtISO` — null when the phone has no touch in range
 * (never reached by a broadcast, or only reached more than 30 days
 * before this deal was created).
 */
export function findLastTouch(
  touches: BroadcastTouch[] | undefined,
  dealCreatedAtISO: string,
): BroadcastTouch | null {
  if (!touches || touches.length === 0) return null
  const dealTime = new Date(dealCreatedAtISO).getTime()
  const windowStartTime = dealTime - BROADCAST_ATTRIBUTION_WINDOW_DAYS * 86_400_000

  let best: BroadcastTouch | null = null
  let bestTime = -Infinity
  for (const touch of touches) {
    const t = new Date(touch.createdAt).getTime()
    if (t <= dealTime && t >= windowStartTime && t > bestTime) {
      best = touch
      bestTime = t
    }
  }
  return best
}

/** `sinceISO`/`untilISO` to pass to loadTouchesByPhone so every deal in
 *  `createdAts` can resolve a touch up to BROADCAST_ATTRIBUTION_WINDOW_DAYS
 *  before its own created_at — narrower than "the whole account's
 *  history" (expensive) but wide enough to never miss a valid touch
 *  just because it falls outside the report's selected period (the
 *  FIEB case: a touch sent before the period started still counts if
 *  it's within 30 days of the deal it generated). Null bounds mean no
 *  deals were given — caller should skip the lookup entirely.
 */
export function touchWindowFor(createdAts: string[]): { sinceISO: string; untilISO: string } | null {
  if (createdAts.length === 0) return null
  let min = Infinity
  let max = -Infinity
  for (const iso of createdAts) {
    const t = new Date(iso).getTime()
    if (t < min) min = t
    if (t > max) max = t
  }
  return {
    sinceISO: new Date(min - BROADCAST_ATTRIBUTION_WINDOW_DAYS * 86_400_000).toISOString(),
    untilISO: new Date(max).toISOString(),
  }
}
